const category = (name: string) =>
  BASIC.includes(name)
    ? "basic"
    : name.startsWith("MyObjectBuilder_")
      ? "blocks"
      : /^(AH_|Icon|Arrow|Cross|Danger|Warning|DecorativeBracket)/.test(name) ||
          [
            "Construction",
            "No Entry",
            "Screen_LoadingBar",
            "Screen_LoadingBar2",
          ].includes(name)
        ? "symbols"
        : "textures";
export const SPRITE_GROUPS = (
  ["basic", "symbols", "blocks", "textures"] as const
).map((key) => ({
  key,
  names:
    key === "basic"
      ? BASIC.filter((name) => SPRITE_NAMES.includes(name))
      : SPRITE_NAMES.filter((name) => category(name) === key),
}));
